def set_run_font(run, name="Times New Roman", size=14, bold=False, italic=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def set_para(p, size=14, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=True, space_after=6):
    p.alignment = align
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(0)
    if first_line and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        p.paragraph_format.first_line_indent = Cm(1.25)
    else:
        p.paragraph_format.first_line_indent = Cm(0)
    for run in p.runs:
        set_run_font(run, size=size, bold=bold)


def add_text(doc, text, size=14, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=True, space_after=6):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    set_para(p, size=size, bold=bold, align=align, first_line=first_line, space_after=space_after)
    return p


def add_center(doc, text, size=14, bold=False, space_after=6):
    return add_text(doc, text, size=size, bold=bold, align=WD_ALIGN_PARAGRAPH.CENTER, first_line=False, space_after=space_after)


def add_heading_custom(doc, text, level=1):
    p = doc.add_paragraph()
    run = p.add_run(text)
    size = 16 if level == 1 else 14
    set_run_font(run, size=size, bold=True)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(10)
    p.paragraph_format.first_line_indent = Cm(0)
    return p


